const DICTS: Record<Lang, Record<string, string>> = {
// eslint-disable-next-line @typescript-eslint/no-explicit-any
  en,
  zhHans,
  zhHant: { ...zhHans, ...(zhHant as Record<string, string>) },
  ja: { ...en, ...(ja as Record<string, string>) },
};

/** Translate `key` in the language selected in settings. */
export function t(key: string, params?: Record<string, string | number>): string {
  const lang = (useStore.getState().settings.lang ?? 'en') as Lang;
  const s = DICTS[lang]?.[key] ?? en[key] ?? key;
  if (!params) return s;
  let out = s;
  for (const [k, v] of Object.entries(params))
    out = out.split(`{${k}}`).join(String(v));
  return out;
}
